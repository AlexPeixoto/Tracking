"""Android devices (phones, handhelds such as the AYN Thor) connected by USB.

Android doesn't lend its storage to the PC as a drive: it answers file requests over MTP,
so Windows shows a "portable device" with storages inside ("Internal shared storage", the
SD card) and no drive letter. We read them through Windows' own device API (WPD, a COM
interface, via comtypes): the folder tree is stored exactly like a drive's snapshot and
the scanner reads it from there. Games on the device show up in the library by folder and
file names; their files can't be opened or played from the PC.

Every device that's plugged in is listed; nothing has to be set up on it.
"""

from __future__ import annotations

import ctypes
import logging
import os
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from dataclasses import dataclass

log = logging.getLogger(__name__)

PREFIX = "mtp:"  # volume uid of a device storage: "mtp:<device serial>:<storage name>"
# Folders at the top of a storage that are never a library: app data (huge, mostly not
# readable over USB) and the system's own.
SKIP_TOP = {"android", "lost.dir", "system volume information"}

_OBJ = "{EF6B490D-5CD8-437A-AFFC-DA8B60EE4A3C}"   # WPD_OBJECT_PROPERTIES_V1
_DEV = "{26D4979A-E643-4626-9E2B-736DC0C92FDC}"   # WPD_DEVICE_PROPERTIES_V1
_STORAGE = "{01A3057A-74D6-4E80-BEA7-DC4C212CE50A}"  # WPD_STORAGE_OBJECT_PROPERTIES_V1
_FOLDER = "{27E2E392-A111-48E0-AB0C-E17705A05F85}"   # WPD_CONTENT_TYPE_FOLDER
_FUNCTIONAL = "{99ED0160-17FF-4C44-9D98-1D7A6F941921}"  # storages, and the like


class DeviceOffline(Exception):
    """The device (or that storage / folder on it) isn't connected right now."""


@dataclass(frozen=True)
class Storage:
    device: str      # "AYN Thor"
    storage: str     # "Internal shared storage", "disk" (the SD card)...
    device_id: str   # Windows' id for the device while it's plugged in
    object_id: str   # the storage's id on the device
    uid: str         # stable: survives unplugging and another USB port
    size: int | None = None

    @property
    def label(self) -> str:
        return f"{self.device} · {self.storage}"


def available() -> bool:
    if os.name != "nt":
        return False
    try:
        import comtypes.client  # noqa: F401
    except ImportError:
        return False
    return True


# --------------------------------------------------------------------------- COM plumbing

class _Api:
    """The WPD type libraries (generated by comtypes on first use) and the keys we read."""

    def __init__(self):
        import comtypes
        import comtypes.client as cc

        cc.GetModule("portabledeviceapi.dll")
        cc.GetModule("portabledevicetypes.dll")
        import comtypes.gen.PortableDeviceApiLib as api
        import comtypes.gen.PortableDeviceTypesLib as types

        self.comtypes, self.cc, self.api, self.types = comtypes, cc, api, types
        self.guid = comtypes.GUID
        self.folder, self.functional = comtypes.GUID(_FOLDER), comtypes.GUID(_FUNCTIONAL)

    def key(self, fmtid: str, pid: int, lib=None):
        # Each type library declares its own PROPERTYKEY: values the device returns want
        # the API library's, key collections the types library's.
        k = (lib or self.api)._tagpropertykey()
        k.fmtid, k.pid = self.guid(fmtid), pid
        return ctypes.pointer(k)

    def create(self, cls, iface):
        return self.cc.CreateObject(cls, clsctx=self.comtypes.CLSCTX_INPROC_SERVER, interface=iface)


@contextmanager
def _com() -> Iterator[_Api]:
    """COM for this thread (scans run on worker threads) and the API."""
    import comtypes

    comtypes.CoInitialize()
    try:
        yield _Api()
    finally:
        comtypes.CoUninitialize()


class _Device:
    """One opened device: list children of an object, read a few properties."""

    def __init__(self, a: _Api, device_id: str):
        self.a = a
        info = a.create(a.types.PortableDeviceValues, a.types.IPortableDeviceValues)
        self.dev = a.create(a.api.PortableDevice, a.api.IPortableDevice)
        self.dev.Open(device_id, info)
        self.content = self.dev.Content()
        self.props = self.content.Properties()
        self.keys = a.create(a.types.PortableDeviceKeyCollection, a.types.IPortableDeviceKeyCollection)
        for pid in (4, 7, 11, 12):  # name, content type, size, original file name
            self.keys.Add(a.key(_OBJ, pid, a.types))
        self.k_name, self.k_type = a.key(_OBJ, 4), a.key(_OBJ, 7)
        self.k_size, self.k_file = a.key(_OBJ, 11), a.key(_OBJ, 12)

    def close(self) -> None:
        try:
            self.dev.Close()
        except Exception:
            pass

    def children(self, object_id: str) -> list[str]:
        en = self.content.EnumObjects(0, object_id, None)
        out: list[str] = []
        while True:
            batch = (ctypes.c_wchar_p * 128)()
            got = ctypes.c_ulong(0)
            # The generated wrapper mangles this array argument: call the raw method.
            en._IEnumPortableDeviceObjectIDs__com_Next(
                128, ctypes.cast(batch, ctypes.POINTER(ctypes.c_wchar_p)), ctypes.byref(got))
            out += [batch[i] for i in range(got.value)]
            if got.value < 128:
                return out

    def info(self, object_id: str) -> tuple[str, bool, int]:
        """(name, is a folder, size) of a file / folder / storage."""
        v = self.props.GetValues(object_id, self.keys)

        def get(fn, key, default):
            try:
                return fn(key)
            except Exception:
                return default

        name = get(v.GetStringValue, self.k_file, None) or get(v.GetStringValue, self.k_name, "")
        kind = get(v.GetGuidValue, self.k_type, None)
        size = get(v.GetUnsignedLargeIntegerValue, self.k_size, 0)
        return name, kind in (self.a.folder, self.a.functional), int(size or 0)

    def string(self, object_id: str, fmtid: str, pid: int) -> str | None:
        try:
            return self.props.GetValues(object_id, None).GetStringValue(self.a.key(fmtid, pid))
        except Exception:
            return None

    def number(self, object_id: str, fmtid: str, pid: int) -> int | None:
        try:
            return int(self.props.GetValues(object_id, None).GetUnsignedLargeIntegerValue(
                self.a.key(fmtid, pid)))
        except Exception:
            return None


def _device_ids(a: _Api) -> list[str]:
    mgr = a.create(a.api.PortableDeviceManager, a.api.IPortableDeviceManager)
    try:
        mgr.RefreshDeviceList()
    except Exception:
        pass
    n = ctypes.c_ulong(0)
    mgr._IPortableDeviceManager__com_GetDevices(None, ctypes.byref(n))
    if not n.value:
        return []
    ids = (ctypes.c_wchar_p * n.value)()
    mgr._IPortableDeviceManager__com_GetDevices(ctypes.cast(ids, ctypes.POINTER(ctypes.c_wchar_p)),
                                               ctypes.byref(n))
    return [i for i in ids[: n.value] if i]


def _friendly_name(a: _Api, device_id: str) -> str | None:
    mgr = a.create(a.api.PortableDeviceManager, a.api.IPortableDeviceManager)
    n = ctypes.c_ulong(0)
    try:
        mgr._IPortableDeviceManager__com_GetDeviceFriendlyName(device_id, None, ctypes.byref(n))
        buf = ctypes.create_unicode_buffer(max(n.value, 1))
        mgr._IPortableDeviceManager__com_GetDeviceFriendlyName(
            device_id, ctypes.cast(buf, ctypes.POINTER(ctypes.c_ushort)), ctypes.byref(n))
        return buf.value or None
    except Exception:
        return None


# --------------------------------------------------------------------------- public

def list_storages() -> list[Storage]:
    """Every storage of every connected device ([] when there are none / not Windows)."""
    if not available():
        return []
    found = []
    try:
        with _com() as a:
            for did in _device_ids(a):
                try:
                    dev = _Device(a, did)
                except Exception as e:  # a device that refuses (locked phone...)
                    log.info("can't open device %s: %s", did, e)
                    continue
                try:
                    name = (_friendly_name(a, did) or dev.string("DEVICE", _DEV, 12)
                            or dev.string("DEVICE", _DEV, 8) or "Device")
                    serial = dev.string("DEVICE", _DEV, 9) or did
                    for sid in dev.children("DEVICE"):
                        storage, _, _ = dev.info(sid)
                        found.append(Storage(name, storage or sid, did, sid,
                                             f"{PREFIX}{serial.lower()}:{storage or sid}",
                                             dev.number(sid, _STORAGE, 4)))
                finally:
                    dev.close()
    except Exception as e:
        log.warning("couldn't list devices: %s", e)
    return found


def find(uid: str, storages: list[Storage] | None = None) -> Storage | None:
    for s in storages if storages is not None else list_storages():
        if s.uid == uid:
            return s
    return None


def _locate(dev: _Device, st: Storage, folder: str) -> str:
    """The object id of ``folder`` ("Emulation/roms") on the storage."""
    oid = st.object_id
    for part in [p for p in folder.split("/") if p]:
        nxt = next((c for c in dev.children(oid) if dev.info(c)[0].lower() == part.lower()), None)
        if nxt is None:
            raise DeviceOffline(f"{st.label}/{folder}")
        oid = nxt
    return oid


def list_folders(st: Storage, folder: str = "") -> list[str]:
    """Sub-folders of ``folder`` on the storage (for picking a location)."""
    with _com() as a:
        dev = _Device(a, st.device_id)
        try:
            oid = _locate(dev, st, folder)
            names = []
            for c in dev.children(oid):
                name, is_dir, _ = dev.info(c)
                if is_dir and not name.startswith(".") and not (not folder and name.lower() in SKIP_TOP):
                    names.append(name)
            return sorted(names, key=str.lower)
        finally:
            dev.close()


def read_tree(st: Storage, folder: str = "", progress: Callable[[str], None] | None = None,
              cancelled: Callable[[], bool] = lambda: False) -> dict[str, list[list]]:
    """Every folder under ``folder``: {rel folder: [[name, is_dir, size, 0]]}, the same
    shape as a drive snapshot. Hidden folders (and Android/ at the top) are left out."""
    try:
        with _com() as a:
            try:
                dev = _Device(a, st.device_id)
            except Exception as e:
                raise DeviceOffline(st.label) from e
            try:
                dirs: dict[str, list[list]] = {}
                todo = [("", _locate(dev, st, folder))]
                while todo and not cancelled():
                    rel, oid = todo.pop()
                    entries = []
                    for c in dev.children(oid):
                        name, is_dir, size = dev.info(c)
                        if not name:
                            continue
                        entries.append([name, is_dir, 0 if is_dir else size, 0.0])
                        skip = name.startswith(".") or (not rel and not folder and name.lower() in SKIP_TOP)
                        if is_dir and not skip:
                            todo.append((f"{rel}/{name}" if rel else name, c))
                    dirs[rel] = entries
                    if progress:
                        progress(f"{st.label}/{folder}/{rel}".replace("//", "/").rstrip("/"))
                return dirs
            finally:
                dev.close()
    except DeviceOffline:
        raise
    except Exception as e:  # unplugged halfway, locked, ...
        raise DeviceOffline(f"{st.label}: {e}") from e
